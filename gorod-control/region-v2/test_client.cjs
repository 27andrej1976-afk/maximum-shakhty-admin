'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),P=require('./web/client.js');
const f=JSON.parse(fs.readFileSync(process.argv[2],'utf8')),now=Date.parse(f.generatedAt);
assert.equal(P.validFeed({...f,events:[{...f.events[0],addresses:null}]}),false,'invalid feed must not replace cached data');
assert.equal(P.visible({...f.events[0],requiresReview:true},now),false,'unreviewed evidence cannot become a marker');
assert.equal(f.dataMode,'test');assert.ok(P.validFeed(f));
const initial={city:'fixture-a',category:'all',scope:'region',home:null,radius:1};
assert.equal(P.select(f,initial,now).length,3);
assert.equal(P.select(f,{...initial,scope:'near'},now).length,1,'region MCHS visible without a point');
assert.equal(P.select(f,{...initial,scope:'near',home:{lat:47.709,lon:40.215}},now).length,3,'nearby addressed events and regional MCHS');
assert.equal(P.select(f,{...initial,scope:'near',home:{lat:48.1,lon:40.8}},now).length,1,'outside radius leaves regional warning');
assert.equal(P.select(f,{...initial,city:'fixture-b'},now).length,1,'same street in a different municipality is not a match');
assert.equal(P.select(f,{...initial,category:'gas'},now).length,0);
assert.equal(P.health(f,'fixture-a',false,now).water.state,'unavailable');
assert.equal(P.health(f,'fixture-a',false,now).power.state,'read');
assert.equal(P.health(f,'fixture-a',false,now).gas.state,'unconfigured');
assert.equal(P.health(f,'fixture-a',true,now).power.state,'unavailable','offline cache must not be green');
assert.equal(P.health(f,'fixture-a',false,now+16*60e3).power.state,'unavailable','stale export must not be green');
assert.equal(P.select(f,initial,now+40*3600e3).length,0,'client also enforces event expiration');
assert.equal(P.safeMax('javascript:alert(1)'),null);assert.equal(P.safeMax('https://max.ru.evil.example/a'),null);
assert.equal(P.point({lat:47,lon:40}),false,'unverified geometry cannot create a marker');
assert.equal(P.point({lat:147,lon:40,geometryVerified:true}),false,'invalid coordinates cannot create a marker');
console.log('Regional client: filtering, geography, offline/stale states, expiry and link policy passed');
